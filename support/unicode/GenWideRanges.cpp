#include <algorithm>
#include <charconv>
#include <cstdio>
#include <cstdint>
#include <fstream>
#include <print>
#include <stdexcept>
#include <string>
#include <string_view>
#include <system_error>
#include <vector>

struct wide_cp_range {
  std::uint32_t first;
  std::uint32_t last;
};

auto trim(std::string_view text) -> std::string_view {
  constexpr auto whitespace = " \t\r";
  const auto first = text.find_first_not_of(whitespace);
  if (first == std::string_view::npos) return {};
  return text.substr(first, text.find_last_not_of(whitespace) - first + 1);
}

auto parse_code_point(std::string_view text) -> std::uint32_t {
  text = trim(text);
  if (text.empty())
    throw std::runtime_error{"missing code point"};

  std::uint32_t value{};
  const auto end = text.data() + text.size();
  const auto [ptr, error] = std::from_chars(text.data(), end, value, 16);
  if (error != std::errc{} || ptr != end || value > 0x10ffff)
    throw std::runtime_error{"invalid code point: " + std::string{text}};
  return value;
}

int main(int argc, char** argv) try {
  if (argc != 2) {
    std::println(stderr, "Usage: {} EastAsianWidth.txt", argv[0]);
    return 2;
  }

  std::ifstream input{argv[1]};
  if (!input)
    throw std::runtime_error{"cannot open " + std::string{argv[1]}};

  std::vector<wide_cp_range> ranges;
  for (std::string line; std::getline(input, line);) {
    const auto view = std::string_view{line};
    const auto row = trim(view.substr(0, view.find('#')));
    if (row.empty()) continue;

    const auto separator = row.find(';');
    if (separator == std::string_view::npos)
      throw std::runtime_error{"missing ';' in: " + line};

    const auto property = trim(row.substr(separator + 1));
    if (property != "W" && property != "F") continue;

    const auto field = trim(row.substr(0, separator));
    const auto dots = field.find("..");
    const auto first = parse_code_point(field.substr(0, dots));
    const auto last = dots == std::string_view::npos
                    ? first : parse_code_point(field.substr(dots + 2));
    if (last < first)
      throw std::runtime_error{"reversed range: " + std::string{field}};

    ranges.push_back({first, last});
  }

  if (input.bad() || !input.eof())
    throw std::runtime_error{"error reading input"};
  if (ranges.empty())
    throw std::runtime_error{"input has no W or F entries"};

  // Additional two-column ranges in C++23 [format.string.std].
  ranges.insert(ranges.end(), {
    {0x4dc0, 0x4dff},
    {0x1f300, 0x1f5ff},
    {0x1f900, 0x1f9ff},
  });
  std::ranges::sort(ranges, {}, &wide_cp_range::first);

  std::vector<wide_cp_range> merged;
  for (const auto& range : ranges) {
    if (merged.empty() || range.first > merged.back().last + 1) {
      merged.push_back(range);
    } else {
      merged.back().last = std::max(merged.back().last, range.last);
    }
  }

  std::print("{}", R"(/**
 * @file EastAsianWidth.hpp
 * @brief Unicode display-width ranges.
 *
 * Generated by support/unicode/GenWideRanges.cpp from
 * support/unicode/EastAsianWidth.txt. Do not modify this file directly.
 * See support/unicode/README.md for download and regeneration instructions.
 */

#include <cstdint>
#pragma once

namespace tjg::color::detail::unicode::detail {

struct wide_cp_range {
  std::uint32_t first;
  std::uint32_t last;
};

inline constexpr wide_cp_range wide_ranges[] = {
)");
  for (const auto& [first, last] : merged)
    std::println("  {{0x{:x}, 0x{:x}}},", first, last);
  std::println("}};\n\n}} // tjg::color::detail::unicode");
} catch (const std::exception& error) {
  std::println(stderr, "{}", error.what());
  return 1;
}
